"""Core domain types. Frozen so stored state only changes through a repo."""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import StrEnum
from typing import Any


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


class RiskTier(StrEnum):
    READ = "READ"    # runs immediately
    WRITE = "WRITE"  # needs user confirmation via the client


class ActionStatus(StrEnum):
    PENDING = "PENDING"
    EXECUTING = "EXECUTING"
    SUCCEEDED = "SUCCEEDED"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"
    EXPIRED = "EXPIRED"
    SUPERSEDED = "SUPERSEDED"


@dataclass(frozen=True)
class PendingAction:
    """A write the LLM proposed. Confirm executes exactly these args."""

    id: str
    session_id: str
    tool: str
    args: dict[str, Any]        # validated snapshot
    summary: str                # what the user sees on the confirm button
    idempotency_key: str        # generated by the gateway, sent to the MCP server
    expires_at: datetime
    status: ActionStatus = ActionStatus.PENDING
    created_at: datetime = field(default_factory=utcnow)
    result: dict[str, Any] | None = None
    error: dict[str, Any] | None = None

    def is_expired(self, now: datetime) -> bool:
        return now >= self.expires_at


@dataclass(frozen=True)
class AuditEntry:
    session_id: str
    event: str                  # e.g. "read", "proposed", "superseded", "succeeded", "denied"
    tool: str
    args: dict[str, Any]
    action_id: str | None = None
    detail: dict[str, Any] | None = None
    at: datetime = field(default_factory=utcnow)
