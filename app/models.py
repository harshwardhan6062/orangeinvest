"""Core domain types. Frozen so stored state only changes through a repo."""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone
from enum import StrEnum
from typing import Any

# India has no DST, so a fixed offset is exact and needs no tzdata.
IST = timezone(timedelta(hours=5, minutes=30), "IST")


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


class RiskTier(StrEnum):
    READ = "READ"    # runs immediately
    WRITE = "WRITE"  # needs user confirmation via the client


class ActionStatus(StrEnum):
    PENDING = "PENDING"
    EXECUTING = "EXECUTING"
    SUCCEEDED = "SUCCEEDED"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"
    EXPIRED = "EXPIRED"
    SUPERSEDED = "SUPERSEDED"
    UNKNOWN = "UNKNOWN"  # no definite answer (timeout, transport, cancelled); confirm retries with the same key


@dataclass(frozen=True)
class PendingAction:
    """A write the LLM proposed. Confirm executes exactly these args."""

    id: str
    session_id: str
    tool: str
    args: dict[str, Any]        # validated snapshot
    summary: str                # what the user sees on the confirm button
    idempotency_key: str        # generated by the gateway, sent to the MCP server
    expires_at: datetime
    status: ActionStatus = ActionStatus.PENDING
    created_at: datetime = field(default_factory=utcnow)
    result: dict[str, Any] | None = None
    error: dict[str, Any] | None = None

    def is_expired(self, now: datetime) -> bool:
        return now >= self.expires_at


class AuditEvent(StrEnum):
    DENIED = "DENIED"            # tool not in the registry
    INVALID = "INVALID"          # validator rejected the args
    READ = "READ"
    READ_FAILED = "READ_FAILED"
    PROPOSED = "PROPOSED"        # write stored as a PendingAction
    SUPERSEDED = "SUPERSEDED"
    CONFIRMED = "CONFIRMED"      # user confirmed; execution starting
    SUCCEEDED = "SUCCEEDED"
    FAILED = "FAILED"
    UNKNOWN = "UNKNOWN"          # outcome unknown; safe to retry with the same key
    CANCELLED = "CANCELLED"
    EXPIRED = "EXPIRED"
    REFUSED = "REFUSED"          # the model declined a turn (no tool involved)


@dataclass(frozen=True)
class AuditEntry:
    session_id: str
    event: AuditEvent
    tool: str | None = None      # None for events that aren't about a tool call
    args: dict[str, Any] = field(default_factory=dict)
    action_id: str | None = None
    detail: dict[str, Any] | None = None
    at: datetime = field(default_factory=utcnow)


@dataclass(frozen=True)
class ToolContext:
    """What validators, summaries and recorders may see.

    `facts` is this session's cache of what the server has told us (search
    results, offered slots). JSON-shaped so it can live in Postgres later.
    Recorders mutate it; the gateway saves it.
    """

    now: datetime
    facts: dict[str, Any]
